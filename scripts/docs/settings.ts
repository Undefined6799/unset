// Settings pages for the Hugo docs (P1.21a): one place to see every value that can be changed, read from the files
// that hold it, so the pages cannot drift. Nothing here is a second copy: each row names its source. The readers are
// settings-process.ts (process settings) and settings-sources.ts (the rest); this file renders, checks and writes.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { cell, code, type Row, type Setting, STACKS } from "./settings-process.ts";
import { loadSettingsModel, NOTES, SECURITY_KEYS, type SettingsModel } from "./settings-sources.ts";

export { readPdsAdminSettings, stackCell } from "./settings-process.ts";
export { loadSettingsModel, memberPages } from "./settings-sources.ts";

const CONTENT_DIR = "docs/site/content/settings";
const SWITCH_KINDS = new Set(["bool", "oneOf"]);
const STACK_NAMES = STACKS.map((s) => s.name);

function table(head: readonly string[], rows: readonly Row[]): string[] {
  if (rows.length === 0) return ["None."];
  return [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ];
}

function page(title: string, weight: number, intro: readonly string[], body: readonly string[]): string {
  const head = [
    "---",
    `title: ${title}`,
    `weight: ${weight}`,
    "---",
    "",
    "Generated by `scripts/docs/settings.ts`. Do not edit.",
  ];
  return `${[...head, "", ...intro, ...body].join("\n").trimEnd()}\n`;
}

const settingRow = (p: string, s: Setting): Row => [
  code(p),
  code(s.key),
  s.kind,
  cell(s.allowed),
  s.fallback,
  ...s.stacks,
  `\`${s.source}\``,
];
const SETTING_HEAD = ["Process", "Key", "Kind", "Allowed", "Default", ...STACK_NAMES, "Defined in"];

function indexPage(): string {
  return page(
    "Settings",
    6,
    [
      "Every value that can be changed in the app, in one place, read from the files that hold it. The settings stay where they live; these pages only gather them. To change one, edit the file a row names.",
      "",
      "Two kinds of value:",
      "",
      "- **Configurable**: read from the environment at start, set per stack in a compose file. A bad value stops the process at boot.",
      "- **Fixed in code**: a constant; changing it is a code change in a PR.",
      "",
      `Stacks: **local** is \`${STACKS[0].file}\`, **staging** is \`${STACKS[1].file}\` (the stack staging runs, built from source). There is no production stack yet (step P5.00). "from env file" names a variable in the stack's interpolation file, which lives outside the checkout. Secrets show only their name and that they are required.`,
      "",
      "| Page | What it lists |",
      "| --- | --- |",
      "| [Switches](switches/) | Settings that turn something on or off, or choose a mode |",
      "| [Sizes and limits](limits/) | Edge and app rate limits, container limits, and limits fixed in code |",
      "| [Security](security/) | Security headers, page CSPs and the settings with a security role |",
      "| [Process settings](processes/) | Every environment setting of every process and service |",
      "| [Member settings](member/) | The settings pages members use |",
    ],
    [],
  );
}

function switchesPage(model: SettingsModel): string {
  const rows = model.processes.flatMap((p) =>
    p.settings
      .filter((s) => SWITCH_KINDS.has(s.kind) || s.allowed === "true or false")
      .map((s) => settingRow(p.process, s)),
  );
  const isFlag = (value: string | undefined) => value === "`true`" || value === "`false`";
  const shipped = model.otherServices.flatMap((s) =>
    s.rows.filter((r) => r.slice(1).some(isFlag)).map((r) => [code(s.service), ...r]),
  );
  return page(
    "Switches",
    1,
    ["Settings that turn something on or off or pick a mode. All are configurable per stack."],
    [
      "",
      ...table(SETTING_HEAD, rows),
      "",
      "## Switches of other services",
      "",
      "Set in the compose files for services we run as shipped (see [Process settings](../processes/#other-services)).",
      "",
      ...table(["Service", "Key", ...STACK_NAMES], shipped),
    ],
  );
}

function limitsPage(model: SettingsModel): string {
  const quotas = model.processes.flatMap((p) =>
    p.settings.filter((s) => s.key.startsWith("INVITE_")).map((s) => settingRow(p.process, s)),
  );
  return page(
    "Sizes and limits",
    2,
    [],
    [
      "## Edge rate limits",
      "",
      "Configurable: `deployment/edge/limits.json`, applied in `deployment/edge/snippets/ratelimit.caddy`.",
      "",
      ...table(["Zone or key", "Host", "Limit"], model.edgeZones),
      "",
      "## App rate limits (web)",
      "",
      "Fixed in code: `interfaces/web/src/lib/server/limits.ts`. A route names its policy; the [Endpoints](../../endpoints/) pages show which. In `socket` mode (no edge naming the client) the per-address buckets are dropped.",
      "",
      ...table(["Mode", "Policy", "Scope", "Capacity", "Refill"], model.appPolicies),
      "",
      "## Invite quotas (pds-admin)",
      "",
      ...table(SETTING_HEAD, quotas),
      "",
      "## Container limits",
      "",
      "Configurable per stack in the compose files.",
      "",
      ...table(["Service", ...STACK_NAMES], model.containers),
      "",
      "## Limits fixed in code",
      "",
      ...table(["Name", "Value", "What for", "Defined in"], model.constants),
    ],
  );
}

function securityPage(model: SettingsModel): string {
  const keys = new Set<string>(SECURITY_KEYS);
  const rows = model.processes.flatMap((p) =>
    p.settings.filter((s) => keys.has(s.key)).map((s) => settingRow(p.process, s)),
  );
  return page(
    "Security",
    3,
    [],
    [
      "## Settings with a security role",
      "",
      ...table(SETTING_HEAD, rows),
      "",
      "## Edge headers",
      "",
      "Fixed in config: `deployment/edge/snippets/security-headers.caddy`.",
      "",
      ...table(["Snippet", "Header", "How", "Value"], model.edgeHeaders),
      "",
      "## Web headers on every response",
      "",
      "Fixed in code: `shared/http/csp/headers.ts`. These are the `static` group's headers, which web sends on every response (`interfaces/web/server.ts`); origins are shown by their setting name. The `media` group differs, since other sites embed it: `referrer-policy: no-referrer` and `cross-origin-resource-policy: cross-origin`.",
      "",
      ...table(["Header", "Value"], model.webHeaders),
      "",
      "## Page CSP by group",
      "",
      "Fixed in code: `interfaces/web/src/lib/server/csp.ts`.",
      "",
      ...table(["Group", "Content-Security-Policy"], model.pageCsp),
    ],
  );
}

function processesPage(model: SettingsModel): string {
  const body: string[] = [];
  for (const p of model.processes) {
    body.push(
      "",
      `## ${p.process}`,
      "",
      ...table(
        SETTING_HEAD.slice(1),
        p.settings.map((s) => settingRow(p.process, s).slice(1)),
      ),
    );
  }
  body.push(
    "",
    "## Other services",
    "",
    "Services we run as shipped or without a settings schema: the keys each stack sets.",
  );
  for (const s of model.otherServices) body.push("", `### ${s.service}`, "", ...table(["Key", ...STACK_NAMES], s.rows));
  return page(
    "Process settings",
    4,
    ['Every environment setting, by process. "not set" means the default applies.'],
    body,
  );
}

function memberPage(model: SettingsModel): string {
  return page(
    "Member settings",
    5,
    [`What members can set for themselves. Notes are from \`${NOTES}\`.`, ""],
    table(["Page", "What a member sets"], model.memberPages),
  );
}

export function renderSettingsFiles(model: SettingsModel): Map<string, string> {
  return new Map([
    [`${CONTENT_DIR}/_index.md`, indexPage()],
    [`${CONTENT_DIR}/switches.md`, switchesPage(model)],
    [`${CONTENT_DIR}/limits.md`, limitsPage(model)],
    [`${CONTENT_DIR}/security.md`, securityPage(model)],
    [`${CONTENT_DIR}/processes.md`, processesPage(model)],
    [`${CONTENT_DIR}/member.md`, memberPage(model)],
  ]);
}

function diffFiles(root: string, files: ReadonlyMap<string, string>): string[] {
  const problems: string[] = [];
  for (const [rel, text] of files) {
    const abs = join(root, rel);
    if (!existsSync(abs)) problems.push(`${rel} is missing`);
    else if (readFileSync(abs, "utf8") !== text) problems.push(`${rel} differs from the generator`);
  }
  const dir = join(root, CONTENT_DIR);
  if (existsSync(dir)) {
    for (const name of readdirSync(dir)) {
      if (!files.has(`${CONTENT_DIR}/${name}`))
        problems.push(`${CONTENT_DIR}/${name} is not produced by the generator`);
    }
  }
  return problems.sort();
}

/** Problems, or the ways the committed pages differ. Empty means the tree matches. */
export async function checkSettings(root: string): Promise<readonly string[]> {
  const loaded = await loadSettingsModel(root);
  return loaded.ok ? diffFiles(root, renderSettingsFiles(loaded.model)) : loaded.problems;
}

/** Rewrites the pages. Writes nothing when the sources do not check. */
export async function writeSettings(root: string): Promise<readonly string[]> {
  const loaded = await loadSettingsModel(root);
  if (!loaded.ok) return loaded.problems;
  const files = renderSettingsFiles(loaded.model);
  const dir = join(root, CONTENT_DIR);
  if (existsSync(dir))
    for (const name of readdirSync(dir)) if (!files.has(`${CONTENT_DIR}/${name}`)) rmSync(join(dir, name));
  for (const [rel, text] of files) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  }
  return [];
}

if (import.meta.main) {
  const root = join(import.meta.dirname, "..", "..");
  const arg = process.argv[2] ?? "--write";
  if (arg !== "--check" && arg !== "--write") {
    console.error("usage: node scripts/docs/settings.ts [--check|--write]");
    process.exitCode = 2;
  } else {
    const problems = arg === "--check" ? await checkSettings(root) : await writeSettings(root);
    for (const problem of problems) console.error(problem);
    process.exitCode = problems.length === 0 ? 0 : 1;
  }
}
