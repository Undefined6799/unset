// Lexicon build (P1.31): check every schema, then generate the TypeScript validators with `lex build` into
// generated/ (checked in, with its own tsconfig, which the build writes too: the output assumes
// exactOptionalPropertyTypes off, and this package's tsconfig references it). `node
// scripts/build.ts` writes them; `--check` exits 1 when they are out of date. generated_types_current runs the same
// comparison in CI. child_process runs only the pinned lex and biome binaries, by execFile with a fixed argument list.
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import * as doc from "@atproto/lex-document";

const PACKAGE = join(import.meta.dirname, "..");
const REPO = join(PACKAGE, "..", "..");
const GENERATED = join(PACKAGE, "generated");
const FLAT_NSID = /^sh\.unset\.[a-zA-Z][a-zA-Z0-9]*$/;
const SET_PREFIX = "sh.unset.";
/** Consent text languages. English only until the i18n slice adds French (Alex, 2026-10-15, "English first"). */
const LANGUAGES = ["en"];
/** Keys whose values are data, not schema nodes. */
const VALUE_LISTS = new Set(["knownValues", "enum", "default", "const"]);
// Generated code casts recursive refs `as any` (@atproto/lex-builder 0.1.17); the line keeps biome's rule for ours.
const SUPPRESS = "// biome-ignore-all lint/suspicious/noExplicitAny: generated by @atproto/lex, which casts refs.\n";
const GENERATED_TSCONFIG = JSON.stringify({
  extends: "../../../tsconfig.base.json",
  compilerOptions: { composite: true, rootDir: ".", outDir: "../dist/generated", exactOptionalPropertyTypes: false },
  include: ["**/*.ts"],
});

export type SchemaFile = { file: string; doc: unknown; ours: boolean };
type Node = Record<string, unknown>;

/** Our schemas (schemas/) and the vendored ones they or the app use (vendor/). */
export function readSchemas(root = PACKAGE): SchemaFile[] {
  return ["schemas", "vendor"].flatMap((dir) =>
    readdirSync(join(root, dir))
      .filter((name) => name.endsWith(".json"))
      .sort()
      .map((name) => ({
        file: `${dir}/${name}`,
        doc: JSON.parse(readFileSync(join(root, dir, name), "utf8")) as unknown,
        ours: dir === "schemas",
      })),
  );
}

/** Every problem in the given schema files; empty means they may be built. */
export function schemaProblems(files: readonly SchemaFile[]): string[] {
  return [...files.flatMap(fileProblems), ...sharedNames(files)];
}

/** schemas/ and vendor/ are copied into one folder for `lex build`, so a name in both would let one silently win. */
function sharedNames(files: readonly SchemaFile[]): string[] {
  const base = (file: string) => file.slice(file.indexOf("/") + 1);
  const owned = new Set(files.filter((f) => f.ours).map((f) => base(f.file)));
  return files
    .filter((f) => !f.ours && owned.has(base(f.file)))
    .map((f) => `${f.file}: ${base(f.file)} is also in schemas/`);
}

function fileProblems({ file, doc: value, ours }: SchemaFile): string[] {
  {
    const parsed = doc.lexiconDocumentSchema.safeParse(value);
    if (!parsed.success) return [`${file}: invalid lexicon (${parsed.reason.message})`];
    const id = parsed.value.id;
    const problems = unknownKeys(value as Node, "").map((p) => `${file}: ${p}`);
    if (file !== `${file.split("/")[0]}/${id}.json`) problems.push(`${file}: id ${id} does not match the file name`);
    else if (ours && !FLAT_NSID.test(id)) problems.push(`${file}: id ${id} is not a flat sh.unset.<name> NSID`);
    const main = parsed.value.defs.main;
    if (main?.type === "permission-set") problems.push(...permissionSetProblems(main).map((p) => `${file}: ${p}`));
    return problems;
  }
}

// The lexicon parser keeps keys it does not know, so a misspelt constraint ("maxGraphems") would silently drop a
// limit. Each def type may carry only the keys of its schema in @atproto/lex-document 0.1.13.
const KEYS: Record<string, readonly string[]> = Object.fromEntries(
  Object.entries({
    array: doc.lexiconArraySchema,
    blob: doc.lexiconBlobSchema,
    boolean: doc.lexiconBooleanSchema,
    bytes: doc.lexiconBytesSchema,
    "cid-link": doc.lexiconCidLinkSchema,
    integer: doc.lexiconIntegerSchema,
    object: doc.lexiconObjectSchema,
    params: doc.lexiconParameters,
    "permission-set": doc.lexiconPermissionSetSchema,
    procedure: doc.lexiconProcedureSchema,
    query: doc.lexiconQuerySchema,
    record: doc.lexiconRecordSchema,
    ref: doc.lexiconRefSchema,
    string: doc.lexiconStringSchema,
    subscription: doc.lexiconSubscriptionSchema,
    token: doc.lexiconTokenSchema,
    union: doc.lexiconRefUnionSchema,
    unknown: doc.lexiconUnknownSchema,
  }).map(([type, schema]) => [type, Object.keys(schema.shape)]),
);

function unknownKeys(node: Node, path: string): string[] {
  // Permission entries are open dictionaries of scope parameters; permissionSetProblems checks them.
  if (node.type === "permission") return [];
  const own = path === "" ? Object.keys(doc.lexiconDocumentSchema.shape) : KEYS[String(node.type)];
  const here = own ? Object.keys(node).filter((key) => !own.includes(key)) : [];
  const problems = here.map((key) => `unknown key "${key}" at ${path || "the document"}`);
  if (path.endsWith(":lang")) return problems;
  return [...problems, ...childNodes(node, path).flatMap(([child, at]) => unknownKeys(child, at))];
}

/** The schema nodes directly inside `node`, with their paths; value lists such as enum are data, not nodes. */
function childNodes(node: Node, path: string): (readonly [Node, string])[] {
  return Object.entries(node).flatMap(([key, child]) => {
    if (VALUE_LISTS.has(key)) return [];
    const at = path ? `${path}.${key}` : key;
    const items = Array.isArray(child)
      ? child.map((item, i) => [item, `${at}[${i}]`] as const)
      : [[child, at] as const];
    return items.flatMap(([item, itemPath]) => (isNode(item) ? [[item, itemPath] as const] : []));
  });
}

/**
 * The keys a set's entry may carry, per resource: what @atproto/oauth-scopes 0.5.13 reads from it (repo: collection
 * and action; rpc: lxm, aud, inheritAud). The parser keeps any other key and the server ignores it, so a misspelt
 * `action` would grant every action.
 */
const PERMISSION_KEYS = {
  repo: ["type", "resource", "collection", "action"],
  rpc: ["type", "resource", "lxm", "aud", "inheritAud"],
} as const satisfies Record<string, readonly string[]>;

/**
 * A set may grant only repo: and rpc: under its own group prefix, and an rpc: entry must inherit its audience
 * (@atproto/oauth-scopes 0.5.13, dist/scopes/include-scope.js: parseLexPermission, isParentAuthorityOf). Its
 * consent text appears on every user's consent screen; English only until the i18n slice adds French.
 */
export function permissionSetProblems(set: doc.LexiconPermissionSet): string[] {
  const problems = set.permissions.flatMap((permission, i) => {
    const { resource } = permission;
    if (resource !== "repo" && resource !== "rpc")
      return [`permission ${i} has resource "${resource}"; only repo and rpc`];
    const allowed: readonly string[] = PERMISSION_KEYS[resource];
    const unknown = Object.keys(permission).filter((key) => !allowed.includes(key));
    const found = unknown.map((key) => `permission ${i} has unknown key "${key}"`);
    const names = (resource === "repo" ? permission.collection : permission.lxm) as unknown;
    const list = Array.isArray(names) ? names.map(String) : [String(names)];
    const outside = list.filter((nsid) => !nsid.startsWith(SET_PREFIX) || nsid.length <= SET_PREFIX.length);
    found.push(...outside.map((nsid) => `permission ${i} names ${nsid} outside ${SET_PREFIX}`));
    if (resource === "rpc" && permission.aud !== undefined)
      found.push(`permission ${i} has a fixed aud; rpc entries use inheritAud`);
    else if (resource === "rpc" && permission.inheritAud !== true)
      found.push(`permission ${i} does not set inheritAud: true`);
    return found;
  });
  for (const field of ["title", "detail"] as const) {
    if (!set[field]) problems.push(`permission set has no ${field}`);
    const texts = set[`${field}:lang`] ?? {};
    for (const lang of LANGUAGES) if (!texts[lang]) problems.push(`permission set has no "${lang}" ${field}`);
  }
  return problems;
}

/** Runs `lex build` and biome's formatter into a fresh folder; returns its files by relative path. */
function generate(): Map<string, string> {
  const work = mkdtempSync(join(tmpdir(), "lexicons-"));
  try {
    const input = join(work, "in");
    for (const dir of ["schemas", "vendor"]) cpSync(join(PACKAGE, dir), input, { recursive: true });
    const out = join(PACKAGE, `.generated-${process.pid}`);
    execFileSync(
      join(REPO, "node_modules", ".bin", "lex"),
      [
        "build",
        "--lexicons",
        input,
        "--out",
        out,
        "--clear",
        "--pretty",
        "false",
        "--lib",
        "@atproto/lex-schema",
        "--import-ext",
        ".generated.ts",
        "--file-ext",
        ".generated.ts",
        "--index-file",
      ],
      { stdio: "pipe" },
    );
    try {
      writeFileSync(join(out, "tsconfig.json"), GENERATED_TSCONFIG);
      // Formatted (and imports sorted) in place, so biome reads the repository's biome.json as biome ci will.
      execFileSync(join(REPO, "node_modules", ".bin", "biome"), ["check", "--write", "--linter-enabled=false", out], {
        cwd: REPO,
        stdio: "pipe",
      });
      return new Map(listFiles(out).map((file) => [relative(out, file), withSuppression(readFileSync(file, "utf8"))]));
    } finally {
      rmSync(out, { recursive: true, force: true });
    }
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function withSuppression(source: string): string {
  return source.includes(" as any") ? SUPPRESS + source : source;
}

/** Differences between generated/ and a fresh build, as relative paths; empty means current. */
export function generatedDrift(): string[] {
  const fresh = generate();
  const current = new Map(listFiles(GENERATED).map((file) => [relative(GENERATED, file), readFileSync(file, "utf8")]));
  const paths = [...new Set([...fresh.keys(), ...current.keys()])].sort();
  return paths.filter((path) => fresh.get(path) !== current.get(path));
}

function writeGenerated(): void {
  const files = generate();
  rmSync(GENERATED, { recursive: true, force: true });
  for (const [path, source] of files) {
    const target = join(GENERATED, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, source);
  }
}

function listFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name))
    .sort();
}

function isNode(value: unknown): value is Node {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

if (import.meta.main) {
  const problems = schemaProblems(readSchemas());
  if (problems.length > 0) {
    for (const problem of problems) process.stderr.write(`${problem}\n`);
    process.exit(1);
  }
  if (process.argv.includes("--check")) {
    const drift = generatedDrift();
    for (const path of drift) process.stderr.write(`out of date: generated/${path}\n`);
    process.exit(drift.length > 0 ? 1 : 0);
  }
  writeGenerated();
}
